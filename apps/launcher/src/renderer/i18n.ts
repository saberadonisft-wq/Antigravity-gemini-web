export type TranslationKey = keyof typeof translations.vi;

export function t(lang: Language | string | undefined, key: TranslationKey): string {
  const selectedLang = lang === "en" ? "en" : "vi";
  return translations[selectedLang][key] ?? translations.vi[key] ?? key;
}

export function errorText(lang: Language | string | undefined, error: unknown): string {
  const safe = safeUiError(error);
  const keys: Record<string, TranslationKey> = {
    CONFIG_CONFLICT: "errorConflict", OUTCOME_UNKNOWN: "errorUnknown", TIMEOUT: "errorUnknown",
    CANCELLED: "errorCancelled", NATIVE_ROUTE_UNVERIFIED: "errorNative", SERVICE_UNAVAILABLE: "errorService",
    LOGIN_REQUIRED: "errorSignin", BROWSER_USER_ACTION_REQUIRED: "errorSignin", MODEL_UNAVAILABLE: "errorModel",
  };
  return t(lang, keys[safe.code] ?? "errorGeneric") + " (" + safe.code + ")";
}
